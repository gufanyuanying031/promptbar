import Foundation

// User content and API model IDs are never passed through this localizer.
enum AppLanguage {
    static var current: String {
        get { UserDefaults.standard.string(forKey: "PromptBar.language") ?? (Locale.preferredLanguages.first?.hasPrefix("zh") == true ? "zh" : "en") }
        set { UserDefaults.standard.set(newValue, forKey: "PromptBar.language") }
    }
}
func L(_ text: String) -> String {
    guard AppLanguage.current == "en" else { return text }
    if let value = EnglishUI.values[text] { return value }
    // Dynamic status/error messages have a small, controlled set of translated fragments.
    var output = text
    for key in EnglishUI.fragments { output = output.replacingOccurrences(of:key,with:EnglishUI.values[key]!) }
    return output
}
